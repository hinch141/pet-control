'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const {generateKeyPairSync,sign}=require('node:crypto');
const {createAccessVerifier}=require('../access-verifier');
const {publicKey,privateKey}=generateKeyPairSync('rsa',{modulusLength:2048});
const jwk=publicKey.export({format:'jwk'});jwk.kid='test-key';
const audience='0123456789abcdef0123456789abcdef';
const now=()=>1800000000000;
const base={iss:'https://example.cloudflareaccess.com',aud:[audience],iat:1799999900,exp:1800000100,email:'member@example.com',sub:'test'};
const makeToken=(claims=base)=>{const head=Buffer.from(JSON.stringify({alg:'RS256',kid:'test-key'})).toString('base64url');const body=Buffer.from(JSON.stringify(claims)).toString('base64url');const data=head+'.'+body;return data+'.'+sign('RSA-SHA256',Buffer.from(data),privateKey).toString('base64url');};
const verifier=createAccessVerifier({teamDomain:'https://example.cloudflareaccess.com',audience,allowedEmails:['member@example.com'],now,fetchImpl:async()=>({ok:true,json:async()=>({keys:[jwk]})})});
test('accepts correctly signed allowed household token',async()=>{assert.equal((await verifier(makeToken())).email,'member@example.com');});
test('rejects unauthorised household email',async()=>{await assert.rejects(verifier(makeToken({...base,email:'stranger@example.com'})));});
test('rejects expired token',async()=>{await assert.rejects(verifier(makeToken({...base,exp:1799999999})));});
test('rejects wrong audience',async()=>{await assert.rejects(verifier(makeToken({...base,aud:['different']})));});
test('rejects wrong issuer',async()=>{await assert.rejects(verifier(makeToken({...base,iss:'https://attacker.invalid'})));});
test('rejects altered signature',async()=>{const t=makeToken();await assert.rejects(verifier(t.slice(0,-2)+'xx'));});
test('rejects missing token',async()=>{await assert.rejects(verifier(''));});
